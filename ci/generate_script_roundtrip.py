"""Generate exact script-line restoration rules; never use substring replacement."""
from pathlib import Path
import json
import subprocess
import tempfile
import sys

ROOT = Path(__file__).resolve().parents[1]
JAVA = ROOT / 'dex/app/src/main/java/com/xayah/dex'


def main():
    with tempfile.TemporaryDirectory() as tmp:
        harness = Path(tmp) / 'RoundTripGenerator.java'
        harness.write_text('''package com.xayah.dex;
import java.io.*;
import java.nio.charset.StandardCharsets;
public class RoundTripGenerator {
 public static void main(String[] args) throws Exception {
  CCHelper h = new CCHelper();
  BufferedReader r = new BufferedReader(new InputStreamReader(System.in, StandardCharsets.UTF_8));
  BufferedWriter w = new BufferedWriter(new OutputStreamWriter(System.out, StandardCharsets.UTF_8));
  String s; while ((s = r.readLine()) != null) { w.write(h.s2t(h.t2s(s))); w.write(10); } w.flush();
 }
}''', encoding='utf-8')
        subprocess.run(['javac', '-encoding', 'UTF-8', '-d', tmp,
                        str(JAVA / 'CCHelper.java'), str(JAVA / 'OpenCcPhrases.java'), str(JAVA / 'OpenCcPhraseData.java'), str(harness)], check=True)
        original = (ROOT / 'tools/tools.sh').read_bytes()
        assert b'\r' not in original and original.endswith(b'\n'), 'Canonical script must be LF with final newline'
        normalized = subprocess.run(['java', '-cp', tmp, 'com.xayah.dex.RoundTripGenerator'],
                                    input=original, capture_output=True, check=True).stdout
    before = original.decode('utf-8').split('\n')[:-1]
    after = normalized.decode('utf-8').split('\n')[:-1]
    assert len(before) == len(after), 'Conversion changed line count'
    seen = {}
    for raw, translated in zip(before, after):
        if translated in seen and seen[translated] != raw:
            raise ValueError('Ambiguous restoration; requires context: ' + translated)
        seen[translated] = raw
    rules = {k: v for k, v in seen.items() if k != v}
    quote = lambda s: json.dumps(s, ensure_ascii=False)
    code = '''package com.xayah.dex;

import java.util.Collections;
import java.util.HashMap;
import java.util.Map;

// Generated by ci/generate_script_roundtrip.py from the canonical tools.sh.
// Only the explicit s2t-script command uses these exact complete-line rules.
final class ScriptRoundTrip {
    private static final Map<String, String> LINES = create();
    private static Map<String, String> create() {
        Map<String, String> lines = new HashMap<>();
'''
    for converted, raw in rules.items():
        code += '        lines.put(' + quote(converted) + ', ' + quote(raw) + ');\n'
    code += '''        return Collections.unmodifiableMap(lines);
    }
    static String restore(String line) {
        String original = LINES.get(line);
        return original == null ? line : original;
    }
}
'''
    target = JAVA / 'ScriptRoundTrip.java'
    if '--check' in sys.argv:
        assert target.read_bytes() == code.encode('utf-8'), 'Stale script rules; regenerate before building Dex'
    else:
        target.write_text(code, encoding='utf-8', newline='\n')
    assert [rules.get(s, s) for s in after] == before
    # Validate the actual runtime entry point, not just the generator's mapping.
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(['javac', '-encoding', 'UTF-8', '-d', tmp,
                        str(JAVA / 'CCHelper.java'), str(JAVA / 'OpenCcPhrases.java'), str(JAVA / 'OpenCcPhraseData.java'), str(JAVA / 'CCUtil.java'), str(target)], check=True)
        command = ['java', '-cp', tmp, 'com.xayah.dex.CCUtil']
        simplified = subprocess.run(command + ['t2s'], input=original,
                                    capture_output=True, check=True).stdout
        restored = subprocess.run(command + ['s2t-script'], input=simplified,
                                  capture_output=True, check=True).stdout
        assert restored == original, 'Actual CCUtil roundtrip differs from canonical script'
    print(f'Generated {len(rules)} unambiguous complete-line rules; {len(before)} lines verified')


if __name__ == '__main__':
    main()
