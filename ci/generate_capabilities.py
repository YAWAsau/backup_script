"""Generate static Dex/Rust capability declarations; runtime probes remain independent."""
from pathlib import Path
import argparse,json,re
ROOT=Path(__file__).resolve().parent.parent
def generate(check=False):
 data=json.loads((ROOT/'ci/capabilities.json').read_text(encoding='utf8'))
 entries=data['capabilities'];ids=[e['id'] for e in entries]
 assert len(ids)==len(set(ids)), 'Duplicate capability ID'
 for values in data['contracts'].values():
  assert len(values)==len(set(values)) and set(values)<=set(ids),'Invalid capability contract'
 java=ROOT/'dex/app/src/main/java/com/xayah/dex/AppStateEngine.java';old=java.read_text(encoding='utf8')
 start=old.index('        JsonArray capabilities = new JsonArray();');end=old.index('        root.add("capabilities", capabilities);',start)
 quote=lambda x:json.dumps(x,ensure_ascii=False)
 body='        JsonArray capabilities = new JsonArray();\n        // Generated by ci/generate_capabilities.py; edit ci/capabilities.json.\n'
 for e in entries:body+=f'        addCapability(capabilities, {quote(e["id"])}, {str(e["enabled"]).lower()}, {str(e["required"]).lower()}, {quote(e["detail"])});\n'
 outputs={java:old[:start]+body+old[end:]}
 rust=ROOT/'rust/src/json_caps.rs';text=rust.read_text(encoding='utf8')
 for name,values in data['contracts'].items():
  text,count=re.subn(r'const '+name+r':.*?=\s*&\[.*?\];',lambda _:f'const {name}: &[&str] = &'+json.dumps(values,ensure_ascii=False)+';',text,flags=re.S);assert count==1
 outputs[rust]=text.replace('// Capability contracts copied from the v792 consumers.','// Generated contracts from ci/capabilities.json; runtime results are still verified.')
 for path,wanted in outputs.items():
  if check:assert path.read_text(encoding='utf8')==wanted,f'Stale generated capabilities: {path}'
  else:path.write_text(wanted,encoding='utf8',newline='\n')
 print(f'Capability source: {len(entries)} declarations, {len(data["contracts"])} contracts')
if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');generate(parser.parse_args().check)
